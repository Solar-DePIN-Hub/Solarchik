const DICT: Record<Locale, Record<Key, string>> = {
  en: EN,
  uk: UK,
  es: ES,
  pt: PT,
  de: DE,
  ja: JA,
};

export function isLocale(id: string): id is Locale {
  return (LOCALES as readonly string[]).includes(id);
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const raw = (navigator.language || "en").toLowerCase();
  const two = raw.slice(0, 2);
  if (two === "ru") return "en";
  if (isLocale(two)) return two;
  return "en";
}

export type TFunc = (key: Key, vars?: Record<string, string | number>) => string;

export function t(locale: Locale | string | undefined, key: Key, vars?: Record<string, string | number>): string {
  try {
    const loc: Locale = isLocale(String(locale ?? "")) ? (locale as Locale) : "en";
    let s = DICT[loc]?.[key] ?? EN[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  } catch {
    return String(key);
  }
}

export function makeT(locale: Locale | string | undefined): TFunc {
  const loc: Locale = isLocale(String(locale ?? "")) ? (locale as Locale) : "en";
  return (key, vars) => t(loc, key, vars);
}
